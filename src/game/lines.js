/** 不重複地挑台詞（同一局用過的先不用） */
export class LinePicker {
  constructor(rng = Math.random) {
    this.used = new Set();
    this.rng = rng;
  }
  reset() { this.used.clear(); }
  pick(personaId, situation) {
    const list = LINES[personaId]?.[situation];
    if (!list?.length) return null;
    let fresh = list.filter(l => !this.used.has(l));
    if (!fresh.length) fresh = list;
    const line = fresh[Math.floor(this.rng() * fresh.length)];
    this.used.add(line);
    return line;
  }
}
